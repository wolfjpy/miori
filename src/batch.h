#pragma once
#include "engine.h"
#include "metal.h"
#include "weights.h"
#include <cstdint>
#include <string>
#include <vector>

namespace miori {

// C2 — minimal multi-sequence batch decode (Bmax = 4).
//
// One shared bf16 tensor-core weight cache (owned by Engine) serves every slot.
// Each slot owns its KV cache (11 attention layers) and conv state (13 layers),
// so one decode step runs one token per slot in a single command buffer.
//
// Prompt prefill reuses a single Engine sequentially: Engine::reset, prefill,
// sample the first token, then the used KV positions and live conv state are
// copied into the batch slot. Prefill itself is therefore not batched.
class BatchEngine {
public:
    static constexpr int kBmax = 4;
    static constexpr int kRows = 64;      // MPP 64-row tile granularity
    static constexpr int kHidden = 2048;
    static constexpr int kFfn = 7680;
    static constexpr int kVocab = 128000;
    static constexpr int kKvHeads = 4;
    static constexpr int kHeadDim = 128;
    static constexpr int kQDim = 16 * kHeadDim;   // 2048
    static constexpr int kKvDim = kKvHeads * kHeadDim;  // 512
    static constexpr int kMaxSeq = 4096;
    static constexpr int kLayers = 24;
    static constexpr int kConvState = 6 * kHidden;

    // Weight-streaming strategy for the batched linear layers.
    //   MppBf16 (default): gemm_mpp over the shared bf16 tensor-core cache.
    //   Gemv4:             one 4-bit GEMV pass per weight row for all slots.
    enum class Kernels { MppBf16 = 0, Gemv4 = 1 };

    BatchEngine(Metal& m, Weights& w, Engine& eng) : m_(m), w_(w), eng_(eng) {}
    bool init(std::string& err);
    void set_kernels(Kernels k) { kernels_ = k; }
    const char* kernels_name() const {
        return kernels_ == Kernels::MppBf16 ? "gemm_mpp(bf16)" : "gemv4_b(4-bit)";
    }

    // Prefill `prompt` with the shared Engine, copy its KV/conv state into a
    // free slot and keep the first sampled token. Returns the slot id, or -1.
    // max_new_tokens bounds how many tokens the slot generates.
    int add_sequence(const std::vector<int>& prompt, int max_new_tokens = 16);

    // Feeds one token per running slot in one command buffer, greedily samples
    // one token per slot. Returns the number of tokens generated by this step.
    int decode_step();

    int active() const;      // slots holding a sequence (finished or not)
    int running() const;     // slots still generating
    bool finished(int slot) const { return slot_valid(slot) && slots_[slot].finished; }
    int pos(int slot) const { return slot_valid(slot) ? slots_[slot].pos : 0; }
    const std::vector<int>& tokens(int slot) const { return slots_[slot].tokens; }
    const std::vector<int>& generated(int slot) const { return slots_[slot].generated; }

    void release_slot(int s) {
        if (s >= 0 && s < kBmax) { slots_[s].active = false; slots_[s].finished = false; }
    }
    void clear_slots() {
        for (auto& s : slots_) { s.active = false; s.finished = false; s.tokens.clear(); s.generated.clear(); }
    }
    int steps() const { return steps_; }
    double total_decode_s() const { return total_decode_s_; }
    int total_generated() const { return total_generated_; }

private:
    struct Slot {
        bool active = false;
        bool finished = false;
        int pos = 0;         // next KV write position (number of tokens cached)
        int pending = -1;    // token fed by the next decode_step
        int max_new = 16;
        std::vector<int> tokens;      // prompt + generated
        std::vector<int> generated;   // generated only
    };

    struct Proj {
        uint32_t off = 0;
        uint32_t N = 0;
        uint32_t K = 0;
        const Tensor* wt = nullptr;   // 4-bit weight / scales / biases
        const Tensor* sc = nullptr;
        const Tensor* bi = nullptr;
    };

    struct LayerProj {
        Proj q, k, v, gate, o;    // attention layers
        Proj in, out;             // conv layers
        Proj w1, w2, w3;          // FFN (all layers)
    };

    bool slot_valid(int s) const { return s >= 0 && s < kBmax; }
    void linear(MTL::Buffer* A, MTL::Buffer* C, const Proj& p);
    void linear_gate(MTL::Buffer* A, MTL::Buffer* C, const Proj& p);
    void attn_layer(int layer);
    void conv_layer(int layer);
    void ffn(int layer);
    bool load_weights(std::string& err);

    Metal& m_;
    Weights& w_;
    Engine& eng_;

    LayerProj lw_[kLayers];
    const Tensor* norm_op_[kLayers] = {};
    const Tensor* norm_post_op_[kLayers] = {};
    const Tensor* norm_ffn_[kLayers] = {};
    const Tensor* norm_post_ffn_[kLayers] = {};
    const Tensor* norm_q_[kLayers] = {};
    const Tensor* norm_k_[kLayers] = {};
    const Tensor* kernel_[kLayers] = {};     // conv kernels
    const Tensor* emb_q_ = nullptr;
    const Tensor* emb_s_ = nullptr;
    const Tensor* emb_b_ = nullptr;
    const Tensor* norm_emb_ = nullptr;

    MTL::Buffer* kc_[kLayers] = {};   // [B][4][4096][128] bf16
    MTL::Buffer* vc_[kLayers] = {};   // [B][4][128][4096] bf16
    MTL::Buffer* cs_[kLayers] = {};   // [B][2][6][2048] f32
    int cs_cur_[kLayers] = {};

    // Activations are [kRows][...] so the 64-row MPP tile never reads past the end.
    MTL::Buffer* xb_ = nullptr;       // [64][2048] f32 residual
    MTL::Buffer* hb_ = nullptr;       // [64][2048] bf16
    MTL::Buffer* qb_ = nullptr;       // [64][2048] f32
    MTL::Buffer* kb_ = nullptr;       // [64][512] f32
    MTL::Buffer* vb_ = nullptr;       // [64][512] f32
    MTL::Buffer* gb_ = nullptr;       // [64][16] f32
    MTL::Buffer* qnb_ = nullptr;      // [64][2048] bf16
    MTL::Buffer* knb_ = nullptr;      // [64][512] bf16
    MTL::Buffer* ab_ = nullptr;       // [64][2048] f32 attn out
    MTL::Buffer* agb_ = nullptr;      // [64][2048] bf16 gated attn
    MTL::Buffer* pb_ = nullptr;       // [64][2048] f32 proj
    MTL::Buffer* fgb_ = nullptr;      // [64][7680] f32
    MTL::Buffer* fub_ = nullptr;      // [64][7680] f32
    MTL::Buffer* factb_ = nullptr;    // [64][7680] bf16
    MTL::Buffer* db_ = nullptr;       // [64][2048] f32 down
    MTL::Buffer* bcxb_ = nullptr;     // [64][6144] f32
    MTL::Buffer* gatedb_ = nullptr;   // [64][2048] f32
    MTL::Buffer* hlastb_ = nullptr;   // [64][2048] bf16
    MTL::Buffer* logitsb_ = nullptr;  // [4][128000] f32
    MTL::Buffer* embb_ = nullptr;     // [64][2048] bf16
    MTL::Buffer* tokb_ = nullptr;     // [64] u32
    MTL::Buffer* posb_ = nullptr;     // [64] u32

    MTL::CommandBuffer* cb_ = nullptr;
    MTL::ComputeCommandEncoder* e_ = nullptr;
    Kernels kernels_ = Kernels::MppBf16;
    Slot slots_[kBmax];
    int steps_ = 0;
    double total_decode_s_ = 0.0;
    int total_generated_ = 0;
    bool ready_ = false;
};

}  // namespace miori
