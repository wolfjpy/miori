#include "engine.h"
#include "metal.h"
#include "weights.h"
#include <cstdint>
#include <string>
#include <vector>

namespace miori {

// C2 — multi-sequence batch decode (Bmax = 32) + packed multi-request prefill.
//
// One shared bf16 tensor-core weight cache (owned by Engine) serves every slot.
// Each slot owns its KV cache (11 attention layers) and conv state (13 layers),
// so one decode step runs one token per slot in a single command buffer.
//
// Two prefill paths:
//   add_sequence(): one prompt at a time through the shared Engine, then a
//                   per-head KV copy into the slot. Unchanged (reference path).
//   add_batch():    several short prompts concatenated into one [T][2048]
//                   activation buffer; the 24 layers' GEMMs run once over all T
//                   packed tokens (MPP tensor cores), attention and conv stay
//                   per request on slices of the shared buffers, and KV/conv
//                   state are written straight into the destination slots.
//                   Bit-identical to the add_sequence path for the first token.
class BatchEngine {
public:
    static constexpr int kBmax = 32;
    static constexpr int kRows = 64;      // MPP 64-row tile granularity
    static constexpr int kHidden = 2048;
    static constexpr int kFfn = 7680;
    static constexpr int kVocab = 128000;
    static constexpr int kKvHeads = 4;
    static constexpr int kHeadDim = 128;
    static constexpr int kQDim = 16 * kHeadDim;   // 2048
    static constexpr int kKvDim = kKvHeads * kHeadDim;  // 512
    static constexpr int kMaxSeq = 4096;
    static constexpr int kLayers = 24;
    static constexpr int kConvState = 6 * kHidden;
    // Packed prefill: max concatenated tokens per pass and the per-request
    // attention chunk (mirrors Engine::prefill_ids' 128-token chunking).
    static constexpr int kPackRows = 1024;
    static constexpr int kPackChunk = 128;

    // Weight-streaming strategy for the batched linear layers.
    //   MppBf16 (default): gemm_mpp over the shared bf16 tensor-core cache.
    //   Gemv4:             one 4-bit GEMV pass per weight row for all slots.
    enum class Kernels { MppBf16 = 0, Gemv4 = 1 };

    BatchEngine(Metal& m, Weights& w, Engine& eng) : m_(m), w_(w), eng_(eng) {}
    bool init(std::string& err);
    void set_kernels(Kernels k) { kernels_ = k; }
    const char* kernels_name() const {
        return kernels_ == Kernels::MppBf16 ? "gemm_mpp(bf16)" : "gemv4_b(4-bit)";
    }

    // Prefill `prompt` with the shared Engine, copy its KV/conv state into a
    // free slot and keep the first sampled token. Returns the slot id, or -1.
    // max_new_tokens bounds how many tokens the slot generates.
    int add_sequence(const std::vector<int>& prompt, int max_new_tokens = 16);

    // Packed prefill: prefill all `prompts` in one pass (up to kBmax, at most
    // kPackRows concatenated tokens). Prompts are grouped to fit the free slots
    // and the row budget; a prompt too long to pack falls back to add_sequence().
    // Returns one slot id per prompt, or -1 if it could not be admitted at all.
    std::vector<int> add_batch(const std::vector<std::vector<int>>& prompts,
                               int max_new_tokens = 16);
    // Same, with a per-request max_new_tokens (the server's jobs differ).
    std::vector<int> add_batch(const std::vector<std::vector<int>>& prompts,
                               const std::vector<int>& max_new_tokens);
    // Wall time of the last add_batch() call (all passes), for profiling.
    double last_prefill_s() const { return last_prefill_s_; }
    int last_prefill_tokens() const { return last_prefill_tokens_; }
    int last_prefill_requests() const { return last_prefill_requests_; }
    // True when prompt i of the last add_batch() was prefilled by the packed
    // pass (false = it used the sequential Engine fallback).
    bool was_packed(int i) const {
        return i >= 0 && i < (int)last_packed_.size() && last_packed_[(size_t)i] != 0;
    }
    // First-token logits of prompt i of the last add_batch(), or nullptr when
    // that prompt used the sequential fallback (Engine::logits() holds those).
    // Stable only when MIORI_BATCH_KEEP_LOGITS is set (batch-prefill-test does),
    // otherwise it aliases the last pass buffer and is clobbered by the next one.
    const float* packed_logits(int i) const {
        if (!was_packed(i)) return nullptr;
        if (plogits_) return (const float*)plogits_->contents() + (size_t)i * kVocab;
        return logits_row(last_packed_row_[(size_t)i]);
    }

    // Feeds one token per running slot in one command buffer, greedily samples
    // one token per slot. Returns the number of tokens generated by this step.
    int decode_step();

    int active() const;      // slots holding a sequence (finished or not)
    int running() const;     // slots still generating
    bool finished(int slot) const { return slot_valid(slot) && slots_[slot].finished; }
    int pos(int slot) const { return slot_valid(slot) ? slots_[slot].pos : 0; }
    const std::vector<int>& tokens(int slot) const { return slots_[slot].tokens; }
    const std::vector<int>& generated(int slot) const { return slots_[slot].generated; }

    // Read-only views used by batch-prefill-test to verify the packed prefill
    // against the sequential Engine (byte-for-byte KV / conv state compare).
    MTL::Buffer* slot_kv_k(int layer) const { return kc_[layer]; }
    MTL::Buffer* slot_kv_v(int layer) const { return vc_[layer]; }
    MTL::Buffer* slot_conv_state(int layer) const { return cs_[layer]; }
    int conv_state_cur(int layer) const { return cs_cur_[layer]; }
    // Row i of the packed lm_head output (in group order of the last add_batch).
    const float* logits_row(int i) const {
        return (const float*)logitsb_->contents() + (size_t)i * kVocab;
    }

    void release_slot(int s) {
        if (s >= 0 && s < kBmax) { slots_[s].active = false; slots_[s].finished = false; }
    }
    void clear_slots() {
        for (auto& s : slots_) { s.active = false; s.finished = false; s.tokens.clear(); s.generated.clear(); }
    }
    int steps() const { return steps_; }
    double total_decode_s() const { return total_decode_s_; }
    int total_generated() const { return total_generated_; }

private:
    struct Slot {
        bool active = false;
        bool finished = false;
        int pos = 0;         // next KV write position (number of tokens cached)
        int pending = -1;    // token fed by the next decode_step
        int max_new = 16;
        std::vector<int> tokens;      // prompt + generated
        std::vector<int> generated;   // generated only
    };

    struct Proj {
        uint32_t off = 0;
        uint32_t N = 0;
        uint32_t K = 0;
        const Tensor* wt = nullptr;   // 4-bit weight / scales / biases
        const Tensor* sc = nullptr;
        const Tensor* bi = nullptr;
    };

    struct LayerProj {
        Proj q, k, v, gate, o;    // attention layers
        Proj in, out;             // conv layers
        Proj w1, w2, w3;          // FFN (all layers)
    };

    bool slot_valid(int s) const { return s >= 0 && s < kBmax; }
    void linear(MTL::Buffer* A, MTL::Buffer* C, const Proj& p);
    void linear_gate(MTL::Buffer* A, MTL::Buffer* C, const Proj& p);
    // Packed-prefill variants of the three layer bodies: same math on [T] rows.
    void linear_p(MTL::Buffer* A, MTL::Buffer* C, const Proj& p, int T);
    void linear_gate_p(MTL::Buffer* A, MTL::Buffer* C, const Proj& p, int T);
    void packed_ffn(int layer, int T);
    void packed_attn(int layer, const std::vector<std::vector<int>>& prompts,
                     const std::vector<int>& slots, int T);
    void packed_conv(int layer, const std::vector<std::vector<int>>& prompts,
                     const std::vector<int>& slots, int T);
    bool add_batch_pass(const std::vector<std::vector<int>>& prompts,
                        const std::vector<int>& slots, const std::vector<int>& max_new);
    void attn_layer(int layer);
    void conv_layer(int layer);
    void ffn(int layer);
    bool load_weights(std::string& err);

    Metal& m_;
    Weights& w_;
    Engine& eng_;

    LayerProj lw_[kLayers];
    const Tensor* norm_op_[kLayers] = {};
    const Tensor* norm_post_op_[kLayers] = {};
    const Tensor* norm_ffn_[kLayers] = {};
    const Tensor* norm_post_ffn_[kLayers] = {};
    const Tensor* norm_q_[kLayers] = {};
    const Tensor* norm_k_[kLayers] = {};
    const Tensor* kernel_[kLayers] = {};     // conv kernels
    const Tensor* emb_q_ = nullptr;
    const Tensor* emb_s_ = nullptr;
    const Tensor* emb_b_ = nullptr;
    const Tensor* norm_emb_ = nullptr;

    MTL::Buffer* kc_[kLayers] = {};   // [B][4][4096][128] bf16
    MTL::Buffer* vc_[kLayers] = {};   // [B][4][128][4096] bf16
    MTL::Buffer* cs_[kLayers] = {};   // [B][2][6][2048] f32
    int cs_cur_[kLayers] = {};

    // Activations are [kRows][...] so the 64-row MPP tile never reads past the end.
    MTL::Buffer* xb_ = nullptr;       // [64][2048] f32 residual
    MTL::Buffer* hb_ = nullptr;       // [64][2048] bf16
    MTL::Buffer* qb_ = nullptr;       // [64][2048] f32
    MTL::Buffer* kb_ = nullptr;       // [64][512] f32
    MTL::Buffer* vb_ = nullptr;       // [64][512] f32
    MTL::Buffer* gb_ = nullptr;       // [64][16] f32
    MTL::Buffer* qnb_ = nullptr;      // [64][2048] bf16
    MTL::Buffer* knb_ = nullptr;      // [64][512] bf16
    MTL::Buffer* ab_ = nullptr;       // [64][2048] f32 attn out
    MTL::Buffer* agb_ = nullptr;      // [64][2048] bf16 gated attn
    MTL::Buffer* pb_ = nullptr;       // [64][2048] f32 proj
    MTL::Buffer* fgb_ = nullptr;      // [64][7680] f32
    MTL::Buffer* fub_ = nullptr;      // [64][7680] f32
    MTL::Buffer* factb_ = nullptr;    // [64][7680] bf16
    MTL::Buffer* db_ = nullptr;       // [64][2048] f32 down
    MTL::Buffer* bcxb_ = nullptr;     // [64][6144] f32
    MTL::Buffer* gatedb_ = nullptr;   // [64][2048] f32
    MTL::Buffer* hlastb_ = nullptr;   // [64][2048] bf16
    MTL::Buffer* logitsb_ = nullptr;  // [4][128000] f32
    MTL::Buffer* embb_ = nullptr;     // [64][2048] bf16
    MTL::Buffer* embb16_ = nullptr;   // [128000][2048] bf16
    MTL::Buffer* tokb_ = nullptr;     // [64] u32
    MTL::Buffer* posb_ = nullptr;     // [64] u32

    // ---- packed prefill buffers ([kPackRows] rows unless noted) -------------
    MTL::Buffer* pxb_ = nullptr;      // [T][2048] f32 residual
    MTL::Buffer* phb_ = nullptr;      // [T][2048] bf16 norm out
    MTL::Buffer* pqb_ = nullptr;      // [T][2048] f32 q
    MTL::Buffer* pkb_ = nullptr;      // [T][512]  f32 k (pre-RoPE)
    MTL::Buffer* pvb_ = nullptr;      // [T][512]  f32 v
    MTL::Buffer* pgb_ = nullptr;      // [T][16]   f32 attention gate
    MTL::Buffer* pqnb_ = nullptr;     // [T][2048] bf16 q post-norm/RoPE
    MTL::Buffer* pknb_ = nullptr;     // [T][512]  bf16 k post-norm/RoPE
    MTL::Buffer* pab_ = nullptr;      // [T][2048] f32 attention out
    MTL::Buffer* pagb_ = nullptr;     // [T][2048] bf16 gated attention
    MTL::Buffer* ppb_ = nullptr;      // [T][2048] f32 o_proj / conv out
    MTL::Buffer* pfgb_ = nullptr;     // [T][7680] f32 FFN gate
    MTL::Buffer* pfub_ = nullptr;     // [T][7680] f32 FFN up
    MTL::Buffer* pfactb_ = nullptr;   // [T][7680] bf16 FFN act
    MTL::Buffer* pdb_ = nullptr;      // [T][2048] f32 FFN down
    MTL::Buffer* pbcxb_ = nullptr;    // [T][6144] f32 conv in
    MTL::Buffer* pgatedb_ = nullptr;  // [T][2048] f32 conv gated
    MTL::Buffer* phlastb_ = nullptr;  // [kBmax][2048] bf16 last row per request
    MTL::Buffer* pscores_ = nullptr;  // [kPackChunk][kMaxSeq] f32
    MTL::Buffer* pscores_bf_ = nullptr;  // [kPackChunk][kMaxSeq] bf16
    MTL::Buffer* ppzero_ = nullptr;   // [6][2048] f32 zero conv state (request start)
    MTL::Buffer* ptok_ = nullptr;     // [kPackRows] u32 packed token ids
    MTL::Buffer* pppos_ = nullptr;    // [kPackRows] u32 position within request
    MTL::Buffer* ppslot_ = nullptr;   // [kPackRows] u32 destination slot
    MTL::Buffer* pprow_ = nullptr;    // [kBmax] u32 last packed row per request

    MTL::CommandBuffer* cb_ = nullptr;
    MTL::ComputeCommandEncoder* e_ = nullptr;
    Kernels kernels_ = Kernels::MppBf16;
    Slot slots_[kBmax];
    int steps_ = 0;
    double total_decode_s_ = 0.0;
    int total_generated_ = 0;
    double last_prefill_s_ = 0.0;
    int last_prefill_tokens_ = 0;
    int last_prefill_requests_ = 0;
    std::vector<uint8_t> last_packed_;   // per add_batch() prompt: packed or fallback
    std::vector<int> last_packed_row_;   // per add_batch() prompt: lm_head row, -1
    MTL::Buffer* plogits_ = nullptr;     // [kBmax][kVocab] f32 kept logits (optional)
    bool ready_ = false;
};

}  // namespace miori
